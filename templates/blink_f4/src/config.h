/* Настройки blink под конкретную плату. Меняется только этот файл.
 *
 * Карта регистров RCU/RCC и GPIO — общая для GD32F4xx и STM32F4xx:
 * GPIOA = 0x40020000, шаг порта 0x400; тактирование портов — регистр
 * 0x40023830, бит = номер порта. Проверено на GD32F470; на STM32F4 — по
 * документации, не проверено.
 */
#ifndef CONFIG_H
#define CONFIG_H

/* Порт: 0 = A, 1 = B, 2 = C, 3 = D, 4 = E ... */
#define LED1_PORT       0u
#define LED1_PIN        5u
/* Второй светодиод; LED2_PIN = 0xFFu — нет второго. */
#define LED2_PORT       0u
#define LED2_PIN        0xFFu
/* 1 — светодиод горит при низком уровне (катод на выводе, анод на питании). */
#define LED_ACTIVE_LOW  0

/* Частота ядра после сброса: внутренний RC 16 МГц у обоих семейств. */
#define CORE_HZ         16000000u
/* Полупериод мигания, мс. */
#define HALF_PERIOD_MS  500u

#endif
