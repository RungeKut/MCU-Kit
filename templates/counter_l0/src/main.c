/* Проверка "код идёт" для ST-Link/STM32CubeProgrammer — без единого
 * обращения к периферии.
 *
 * Никакого GPIO, тактирования или таймера: на неизвестной или чужой
 * плате нельзя вслепую переключать выводы — можно задеть то, что
 * управляет реальной нагрузкой (мотор, нагреватель, реле). Единственная
 * цель этого шаблона — доказать, что записанный код выполняется, через
 * растущий счётчик в ОЗУ (knowledge/20_ПРИЁМЫ/20-02), а не показать
 * мигание светодиода. Для платы с известной и безопасной обвязкой GPIO
 * — templates/blink_f4 (Cortex-M4; под M0+ не подходит, другое ядро).
 */
#include <stdint.h>

volatile uint32_t loop_count;

int main(void)
{
    for (;;)
        loop_count++;
}
